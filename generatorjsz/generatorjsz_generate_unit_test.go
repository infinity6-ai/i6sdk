type fakeApi struct {
	spec apiz.ApiSpec
	refs *apiz.DataRefs
}

func (f *fakeApi) ApiSpec() apiz.ApiSpec       { return f.spec }
func (f *fakeApi) GetDataRefs() *apiz.DataRefs { return f.refs }

func objectSchema(fields map[string]*schemaz.Schema) *schemaz.Schema {
	return &schemaz.Schema{
		Object: func(read bool) map[string]*schemaz.Schema { return fields },
	}
}

func stringField() *schemaz.Schema {
	var s string
	return &schemaz.Schema{Raw: func() any { return &s }}
}

func requireJsSyntax(t *testing.T, name, code string) {
	t.Helper()
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("node is not installed")
	}
	path := filepath.Join(t.TempDir(), name+".mjs")
	require.NoError(t, os.WriteFile(path, []byte(code), 0o644))
	out, err := exec.Command("node", "--check", path).CombinedOutput()
	require.NoError(t, err, string(out))
}

func TestManualGenerateWritesOneFilePerApi(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "apigenz") // não existe ainda: Generate cria

	names, err := generatorjsz.Generate(dir, sdkz.All())
	require.NoError(t, err)

	require.Equal(t, []string{"dsz-domain-select.js", "ingestz-get-url.js", "pipez-start.js"}, names)
	for _, name := range names {
		code, err := os.ReadFile(filepath.Join(dir, name))
		require.NoError(t, err)
		require.Contains(t, string(code), "// Code generated by generatorjsz")
		requireJsSyntax(t, name, string(code))
	}
}

func TestManualGenerateIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	read := func() map[string]string {
		out := map[string]string{}
		entries, err := os.ReadDir(dir)
		require.NoError(t, err)
		for _, e := range entries {
			b, err := os.ReadFile(filepath.Join(dir, e.Name()))
			require.NoError(t, err)
			out[e.Name()] = string(b)
		}
		return out
	}

	_, err := generatorjsz.Generate(dir, sdkz.All())
	require.NoError(t, err)
	first := read()
	_, err = generatorjsz.Generate(dir, sdkz.All())
	require.NoError(t, err)

	require.Equal(t, first, read())
}

func TestManualGenerateRemovesOnlyStaleGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}
	write("old-api.js", "// Code generated by generatorjsz from api \"old-api\". DO NOT EDIT.\n")
	write("handwritten.js", "export const x = 1;\n")
	write("apis serao geradas aqui. 1 por api", "")

	_, err := generatorjsz.Generate(dir, sdkz.All())
	require.NoError(t, err)

	require.NoFileExists(t, filepath.Join(dir, "old-api.js"))
	require.FileExists(t, filepath.Join(dir, "handwritten.js"))
	require.FileExists(t, filepath.Join(dir, "apis serao geradas aqui. 1 por api"))
	require.FileExists(t, filepath.Join(dir, "ingestz-get-url.js"))
}

type generateFailureTestScenario struct {
	apis   []apiz.Api
	errMsg string
}

func validApi(id string) *fakeApi {
	return &fakeApi{spec: apiz.ApiSpec{Id: id, Method: "GET", Path: "/api/x"}, refs: &apiz.DataRefs{}}
}

func checkGenerateFailure(t *testing.T, s generateFailureTestScenario) {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "out")
	names, err := generatorjsz.Generate(dir, s.apis)
	require.Error(t, err)
	require.Contains(t, err.Error(), s.errMsg)
	require.Nil(t, names)
	require.NoDirExists(t, dir)
}

func TestManualGenerateFailureInvalidId(t *testing.T) {
	checkGenerateFailure(t, generateFailureTestScenario{
		apis:   []apiz.Api{validApi("ok-api"), validApi("../evil")},
		errMsg: `"../evil"`,
	})
}

func TestManualGenerateFailureTwoApisWithSameId(t *testing.T) {
	checkGenerateFailure(t, generateFailureTestScenario{
		apis:   []apiz.Api{validApi("same-id"), validApi("same-id")},
		errMsg: "mesma função",
	})
}

func TestManualGenerateFailureTwoIdsThatCollapseToSameFunction(t *testing.T) {
	checkGenerateFailure(t, generateFailureTestScenario{
		apis:   []apiz.Api{validApi("get-url"), validApi("get_url")},
		errMsg: "mesma função",
	})
}

func TestManualGenerateFailurePathParamsOutOfSyncWithPath(t *testing.T) {
	api := &fakeApi{
		spec: apiz.ApiSpec{Id: "drift", Method: "GET", Path: "/api/x/{id}"},
		refs: &apiz.DataRefs{},
	}
	checkGenerateFailure(t, generateFailureTestScenario{
		apis:   []apiz.Api{api},
		errMsg: "PathParams",
	})
}

func TestManualGenerateSchemaShapesSameFieldInPathAndBody(t *testing.T) {
	api := &fakeApi{
		spec: apiz.ApiSpec{Id: "dup-field", Method: "POST", Path: "/api/x/{id}"},
		refs: &apiz.DataRefs{
			PathParams: objectSchema(map[string]*schemaz.Schema{"id": stringField()}),
			ReqBody:    objectSchema(map[string]*schemaz.Schema{"id": stringField()}),
		},
	}
	_, _, err := generatorjsz.BuildJsFetch(api.ApiSpec(), api.GetDataRefs())
	require.Error(t, err)
	require.Contains(t, err.Error(), `campo "id" aparece em mais de uma seção`)
}

func TestManualGenerateSchemaShapesApiWithoutRequestFieldsTakesOnlyServices(t *testing.T) {
	api := &fakeApi{
		spec: apiz.ApiSpec{Id: "ping", Method: "GET", Path: "/api/ping"},
		refs: &apiz.DataRefs{},
	}
	fnName, code, err := generatorjsz.BuildJsFetch(api.ApiSpec(), api.GetDataRefs())
	require.NoError(t, err)
	require.Equal(t, "ping", fnName)
	require.Contains(t, code, "export async function ping(services) {")
	require.NotContains(t, code, "PingParams")
	require.NotContains(t, code, "resp.json()")
	requireJsSyntax(t, "ping", code)
}
