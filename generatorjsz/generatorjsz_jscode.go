package generatorjsz

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/infinity6-ai/gox/routez/apiz"
	"github.com/infinity6-ai/gox/schemaz/schemaz"
)

const generatedHeaderPrefix = "// Code generated by generatorjsz"

const servicesTypeImport = "../services/services.js"

// jsIdentRe valida que um nome pode ser identificador JS (função exportada ou propriedade).
var jsIdentRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// apiIdRe valida spec.Id: vira nome de arquivo e, via FuncName, nome de função — por isso só
// letras, dígitos e os separadores "-", "_" e "." (nada de "/" ou "..").
var apiIdRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_.-]*$`)

// idSeparatorRe separa as palavras de um spec.Id para virar camelCase.
var idSeparatorRe = regexp.MustCompile(`[-_.]+`)

// pathParamRe encontra placeholders {name} no ApiSpec.Path.
var pathParamRe = regexp.MustCompile(`\{([A-Za-z0-9_]+)\}`)

// json2HeaderName converte uma chave de schema (com "_") no nome real do header ("-"); é o
// mesmo mapeamento de routez/internal/converter, que não dá pra importar de fora do módulo routez.
func json2HeaderName(k string) string {
	return strings.ReplaceAll(k, "_", "-")
}

// FuncName converte um spec.Id no nome da função JS gerada, ex.: "ingestz-get-url" vira
// "ingestzGetUrl". Devolve erro se o id não puder virar um nome de arquivo/função válido.
func FuncName(id string) (string, error) {
	if !apiIdRe.MatchString(id) {
		return "", fmt.Errorf("generatorjsz: id de api %q inválido (use letras, dígitos, '-', '_' ou '.', começando por letra)", id)
	}
	words := idSeparatorRe.Split(id, -1)
	var b strings.Builder
	for i, w := range words {
		if w == "" {
			continue
		}
		if i > 0 {
			w = strings.ToUpper(w[:1]) + w[1:]
		}
		b.WriteString(w)
	}
	name := b.String()
	if !jsIdentRe.MatchString(name) {
		return "", fmt.Errorf("generatorjsz: id de api %q não gera um identificador JS válido (%q)", id, name)
	}
	return name, nil
}

// FileName é o nome do arquivo gerado para um spec.Id: um arquivo por api.
func FileName(id string) string {
	return id + ".js"
}

type field struct {
	name string
	node *Node
}

// BuildJsFetch gera o JSDoc + função de uma Api, a partir do ApiSpec e dos 6 schemas de
// GetDataRefs.
func BuildJsFetch(spec apiz.ApiSpec, refs *apiz.DataRefs) (fnName string, code string, err error) {
	fnName, err = FuncName(spec.Id)
	if err != nil {
		return "", "", err
	}
	if err := validatePathLiteral(spec.Path); err != nil {
		return "", "", err
	}

	pathFields := introspectFields(refs.PathParams)
	queryFields := introspectFields(refs.QueryParams)
	headerFields := introspectFields(refs.ReqHeaders)
	bodyFields := introspectFields(refs.ReqBody)

	if err := validateFieldNames(pathFields, queryFields, headerFields, bodyFields); err != nil {
		return "", "", err
	}
	if err := validateUniqueFieldNames(pathFields, queryFields, headerFields, bodyFields); err != nil {
		return "", "", err
	}
	if err := validatePathParams(spec.Path, pathFields); err != nil {
		return "", "", err
	}

	respHeaderNode := introspectOptional(refs.RespHeaders)
	respBodyNode := introspectOptional(refs.RespBody)

	allReqFields := concatFields(pathFields, queryFields, headerFields, bodyFields)

	var b strings.Builder
	b.WriteString(buildJsDoc(spec, fnName, allReqFields, respHeaderNode, respBodyNode))
	if len(allReqFields) > 0 {
		fmt.Fprintf(&b, "export async function %s(services, params) {\n", fnName)
	} else {
		fmt.Fprintf(&b, "export async function %s(services) {\n", fnName)
	}
	b.WriteString(buildJsRequest(spec, queryFields, headerFields, bodyFields))
	b.WriteString(buildJsResult(respHeaderNode, respBodyNode))
	b.WriteString("}\n")
	return fnName, b.String(), nil
}

func introspectOptional(schema *schemaz.Schema) *Node {
	if schema == nil {
		return nil
	}
	return Introspect(schema)
}

// introspectFields lê um schema de nível superior (sempre um Object, uma seção do DataRefs) e
// devolve seus campos já ordenados; nil vira lista vazia (a seção não existe para essa Api).
func introspectFields(schema *schemaz.Schema) []field {
	if schema == nil {
		return nil
	}
	n := Introspect(schema)
	fields := make([]field, 0, len(n.FieldOrder))
	for _, name := range n.FieldOrder {
		fields = append(fields, field{name: name, node: n.Fields[name]})
	}
	return fields
}

func concatFields(groups ...[]field) []field {
	var out []field
	for _, g := range groups {
		out = append(out, g...)
	}
	return out
}

func validatePathLiteral(path string) error {
	if strings.ContainsAny(path, "`\\") || strings.Contains(path, "${") {
		return fmt.Errorf("generatorjsz: path %q tem caractere que não pode entrar num template literal JS", path)
	}
	return nil
}

func validateFieldNames(groups ...[]field) error {
	for _, g := range groups {
		for _, f := range g {
			if !jsIdentRe.MatchString(f.name) {
				return fmt.Errorf("generatorjsz: campo %q não é um identificador JS válido", f.name)
			}
		}
	}
	return nil
}

func validateUniqueFieldNames(groups ...[]field) error {
	seen := map[string]bool{}
	for _, g := range groups {
		for _, f := range g {
			if seen[f.name] {
				return fmt.Errorf("generatorjsz: campo %q aparece em mais de uma seção (path/query/headers/body) e colidiria em params", f.name)
			}
			seen[f.name] = true
		}
	}
	return nil
}

func validatePathParams(path string, pathFields []field) error {
	placeholders := map[string]bool{}
	for _, m := range pathParamRe.FindAllStringSubmatch(path, -1) {
		placeholders[m[1]] = true
	}
	declared := map[string]bool{}
	for _, f := range pathFields {
		declared[f.name] = true
	}
	for name := range placeholders {
		if !declared[name] {
			return fmt.Errorf("generatorjsz: path %q referencia {%s}, mas o schema de PathParams não tem esse campo", path, name)
		}
	}
	for name := range declared {
		if !placeholders[name] {
			return fmt.Errorf("generatorjsz: schema de PathParams tem o campo %q, mas o path %q não tem {%s}", name, path, name)
		}
	}
	return nil
}

// jsTypeLiteral renderiza o tipo JSDoc de um Node — "*" cobre tanto nó ausente quanto KindUnknown.
func jsTypeLiteral(n *Node) string {
	if n == nil {
		return "*"
	}
	switch n.Kind {
	case KindString:
		return "string"
	case KindNumber:
		return "number"
	case KindBoolean:
		return "boolean"
	case KindArray:
		return jsTypeLiteral(n.Element) + "[]"
	case KindObject:
		if n.DynamicKeys {
			return "Record<string, " + jsTypeLiteral(n.Element) + ">"
		}
		if len(n.FieldOrder) == 0 {
			return "Object"
		}
		return objectTypeLiteral(n)
	default:
		return "*"
	}
}

// objectTypeLiteral renderiza os campos de um Node objeto como "{a: T, b: U}".
func objectTypeLiteral(n *Node) string {
	parts := make([]string, 0, len(n.FieldOrder))
	for _, name := range n.FieldOrder {
		parts = append(parts, name+": "+jsTypeLiteral(n.Fields[name]))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

// fieldSummary devolve o resumo de um Node, nil-safe em cada nível (Node e Desc podem ser nil).
func fieldSummary(n *Node) string {
	if n == nil || n.Desc == nil {
		return ""
	}
	return n.Desc.Summary
}

// typedefBase é o prefixo PascalCase dos typedefs de uma função: ingestzGetUrl -> IngestzGetUrl.
func typedefBase(fnName string) string {
	return strings.ToUpper(fnName[:1]) + fnName[1:]
}

func buildJsDoc(spec apiz.ApiSpec, fnName string, reqFields []field, respHeaderNode, respBodyNode *Node) string {
	base := typedefBase(fnName)
	var b strings.Builder
	fmt.Fprintf(&b, "%s from api %q. DO NOT EDIT.\n\n", generatedHeaderPrefix, spec.Id)

	if len(reqFields) > 0 {
		fmt.Fprintf(&b, "/**\n * @typedef {Object} %sParams\n", base)
		for _, f := range reqFields {
			typ := jsTypeLiteral(f.node)
			if s := fieldSummary(f.node); s != "" {
				fmt.Fprintf(&b, " * @property {%s} %s - %s\n", typ, f.name, s)
			} else {
				fmt.Fprintf(&b, " * @property {%s} %s\n", typ, f.name)
			}
		}
		b.WriteString(" */\n\n")
	}

	fmt.Fprintf(&b, "/**\n * @typedef {Object} %sResult\n", base)
	b.WriteString(" * @property {number} status - HTTP status code.\n")
	b.WriteString(" * @property {boolean} ok - true when the status is 2xx.\n")
	if respHeaderNode != nil && len(respHeaderNode.FieldOrder) > 0 {
		fmt.Fprintf(&b, " * @property {%s} headers - Response headers, keyed by schema name.\n", objectTypeLiteral(respHeaderNode))
	}
	if respBodyNode != nil {
		fmt.Fprintf(&b, " * @property {%s} [body] - Parsed JSON body, present only when ok.\n", jsTypeLiteral(respBodyNode))
	}
	b.WriteString(" */\n\n")

	b.WriteString("/**\n")
	if spec.Desc != nil {
		if d := spec.Desc(); d != nil && d.Summary != "" {
			fmt.Fprintf(&b, " * %s\n", d.Summary)
		}
	}
	fmt.Fprintf(&b, " * @param {import(%q).Services} services\n", servicesTypeImport)
	if len(reqFields) > 0 {
		fmt.Fprintf(&b, " * @param {%sParams} params\n", base)
	}
	fmt.Fprintf(&b, " * @returns {Promise<%sResult>}\n", base)
	b.WriteString(" */\n")
	return b.String()
}

// buildJsRequest monta a chamada a services.invoker().invoke({...}). Só emite as chaves
// das seções que a Api realmente tem.
func buildJsRequest(spec apiz.ApiSpec, queryFields, headerFields, bodyFields []field) string {
	var b strings.Builder

	jsPath := pathParamRe.ReplaceAllString(strings.TrimPrefix(spec.Path, "/"), "${encodeURIComponent(String(params.$1))}")

	b.WriteString("  const resp = await services.invoker().invoke({\n")
	fmt.Fprintf(&b, "    method: %q,\n", spec.Method)
	fmt.Fprintf(&b, "    path: `%s`,\n", jsPath)

	if len(queryFields) > 0 {
		fmt.Fprintf(&b, "    query: {%s},\n", joinFields(queryFields, func(f field) string {
			return fmt.Sprintf("%q: params.%s", f.name, f.name)
		}))
	}

	if len(headerFields) > 0 {
		fmt.Fprintf(&b, "    headers: {%s},\n", joinFields(headerFields, func(f field) string {
			return fmt.Sprintf("%q: %s", json2HeaderName(f.name), headerValueExpr(f))
		}))
	}

	if len(bodyFields) > 0 {
		fmt.Fprintf(&b, "    json: {%s},\n", joinFields(bodyFields, func(f field) string {
			return f.name + ": " + bodyValueExpr(f)
		}))
	}

	b.WriteString("  });\n")
	return b.String()
}

// joinFields formata fields como "k: v, k2: v2" pra um objeto JS literal, chamando fmtEntry em
// cada campo
func joinFields(fields []field, fmtEntry func(field) string) string {
	entries := make([]string, 0, len(fields))
	for _, f := range fields {
		entries = append(entries, fmtEntry(f))
	}
	return strings.Join(entries, ", ")
}

// headerValueExpr monta a expressão JS de um header: lista vira "a, b", o resto vira String().
func headerValueExpr(f field) string {
	if f.node != nil && f.node.Kind == KindArray {
		return "params." + f.name + `.map(String).join(", ")`
	}
	return "String(params." + f.name + ")"
}

// bodyValueExpr monta a expressão JS de um campo do corpo.
func bodyValueExpr(f field) string {
	if f.node == nil || !f.node.StringArrayWire {
		return "params." + f.name
	}
	if f.node.Kind == KindArray {
		return "params." + f.name + ".map(String)"
	}
	return "[String(params." + f.name + ")]"
}

// buildJsResult monta o objeto {status, ok, headers, body} devolvido pela função gerada.
func buildJsResult(respHeaderNode, respBodyNode *Node) string {
	var b strings.Builder
	b.WriteString("  const result = {status: resp.status, ok: resp.ok};\n")
	if respHeaderNode != nil && len(respHeaderNode.FieldOrder) > 0 {
		b.WriteString("  result.headers = {};\n")
		for _, name := range respHeaderNode.FieldOrder {
			fmt.Fprintf(&b, "  result.headers[%q] = resp.headers.get(%q);\n", name, json2HeaderName(name))
		}
	}
	if respBodyNode != nil {
		b.WriteString("  if (resp.ok) {\n")
		b.WriteString("    result.body = await resp.json();\n")
		b.WriteString("  }\n")
	}
	b.WriteString("  return result;\n")
	return b.String()
}
